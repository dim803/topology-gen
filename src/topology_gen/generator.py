"""
generator.py
------------
Builds the topology generated by a subbasis on a finite set X, in two steps:

1. Basis generation: the basis generated by a subbasis S is the collection
   of all finite intersections of members of S, together with X itself
   (X is the empty intersection). Computed here by closing {X} under
   pairwise intersection with each subbasis member, repeated to a fixed
   point -- any finite intersection of subbasis members can be built by
   intersecting one member at a time, so this reaches every basis element.

2. Topology generation: the topology generated by a basis B is the
   collection of all unions of subsets of B, together with the empty set
   (the empty union). Computed the same way: close {empty set} union B
   under pairwise union with each basis member, to a fixed point.

Since X is finite, "arbitrary unions" and "finite unions" coincide (there
are only finitely many subsets of B to union in the first place), so this
finite fixed-point computation is exact, not an approximation.
"""

from __future__ import annotations


def generate_basis_from_subbasis(X, subbasis) -> set:
    """The basis generated by `subbasis` on the finite set X."""
    X = frozenset(X)
    subbasis = [frozenset(s) for s in subbasis]

    basis = {X}
    changed = True
    while changed:
        changed = False
        new_elements = set()
        for a in basis:
            for s in subbasis:
                inter = a & s
                if inter not in basis and inter not in new_elements:
                    new_elements.add(inter)
        if new_elements:
            basis |= new_elements
            changed = True
    return basis


def generate_topology_from_basis(X, basis) -> set:
    """The topology generated by `basis` on the finite set X."""
    X = frozenset(X)
    basis = {frozenset(b) for b in basis}

    topology = {frozenset()} | basis
    changed = True
    while changed:
        changed = False
        new_sets = set()
        for a in topology:
            for b in basis:
                union = a | b
                if union not in topology and union not in new_sets:
                    new_sets.add(union)
        if new_sets:
            topology |= new_sets
            changed = True
    return topology


def generate_topology_from_subbasis(X, subbasis) -> set:
    """The topology generated by `subbasis` on the finite set X (basis + topology steps)."""
    basis = generate_basis_from_subbasis(X, subbasis)
    return generate_topology_from_basis(X, basis)
